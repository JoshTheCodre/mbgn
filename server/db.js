function pgDriver(connectionString) {
  const pool = new pg.Pool({ connectionString, max: 5, idleTimeoutMillis: 10000, connectionTimeoutMillis: 15000 });
  pool.on('error', (err) => console.error('Database connection error:', err.message));
  const shape = (result) => ({ rows: result.rows, changes: result.rowCount ?? 0 });

  return {
    query: async (sql, params) => shape(await pool.query(sql, params)),
    async transaction(fn) {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const result = await fn({
          query: async (sql, params) => shape(await client.query(sql, params)),
          exec: (sql) => client.query(sql),
        });
        await client.query('COMMIT');
        return result;
      } catch (err) {
        await client.query('ROLLBACK').catch(() => {});
        throw err;
      } finally {
        client.release();
      }
    },
    close: () => pool.end(),
  };
}

// The queries are written with ? for each value; Postgres numbers them.
const toPostgres = (sql) => {
  let n = 0;
  return sql.replace(/'[^']*'|\?/g, (match) => {
    if (match !== '?') return match;
    n += 1;
    return `$${n}`;
  });
};

// Tests pass their own driver, so they can run against an in-memory Postgres.
export async function openDb(config) {
  const driver = config.dbDriver ?? pgDriver(config.databaseUrl);
  const current = new AsyncLocalStorage();
  const run = (sql, params) => (current.getStore() ?? driver).query(toPostgres(sql), params);
  // Writers take turns anyway, so they wait here rather than each holding a
  // connection that ordinary page loads need.
  let writers = Promise.resolve();

  const db = {
    prepare: (sql) => ({
      get: async (...params) => (await run(sql, params)).rows[0],
      all: async (...params) => (await run(sql, params)).rows,
      // An INSERT that needs the new id must say RETURNING id.
      run: async (...params) => {
        const { rows, changes } = await run(sql, params);
        return { changes, lastInsertRowid: rows[0]?.id };
      },
    }),
    transaction(fn) {
      if (current.getStore()) return fn();
      const write = () => driver.transaction((client) => current.run(client, async () => {
        // One writer at a time, across every server. Ranks and totals change together, and
        // this keeps them correct and free of deadlocks however many votes arrive at once.
        await client.query('SELECT pg_advisory_xact_lock(1)');
        return fn();
      }));
      const result = writers.then(write);
      writers = result.catch(() => {});
      return result;
    },
    close: () => driver.close(),
  };

  await driver.transaction(async (client) => {
    await client.query('SELECT pg_advisory_xact_lock(2)');
    await client.exec(SCHEMA);
  });
  return db;
}

export const tx = (db, fn) => db.transaction(fn);

export const nowIso = () => new Date().toISOString();

export async function getSetting(db, key) {
  return (await db.prepare('SELECT value FROM settings WHERE key = ?').get(key))?.value ?? '';
}

export async function setSetting(db, key, value) {
  await db.prepare('INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT (key) DO UPDATE SET value = excluded.value')
    .run(key, String(value));
}
